import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import {
  GOVERNANCE_CRUD_DESCRIPTORS,
  descriptorAllowsAction,
} from '../../src/modules/governance/crudDescriptors.js';
import { governanceEmptyStateBody } from '../../src/modules/governance/governanceEmptyState.js';
import { descriptorPageActions } from '../../src/modules/actionBars.js';
import { ENGLISH_MESSAGES } from '../../src/modules/localization/englishMessages.js';
import { workspaceModuleRouteRecords } from '../../src/modules/index.js';
import { firstRouteActionByKind, routeActionsForContext } from '../../src/modules/routeActions.js';

const root = path.resolve(new URL('../..', import.meta.url).pathname);
const platformAdminContext = { role: 'admin', allPermissions: true };

function routeByName(name) {
  const record = workspaceModuleRouteRecords.find((candidate) => candidate.name === name);
  assert.ok(record, `${name} route missing`);
  return record;
}

function assertLocalizedKey(key, label) {
  assert.ok(key, `${label} key missing`);
  assert.ok(ENGLISH_MESSAGES[key], `${label} has no English fallback`);
}

function translate(key, params = {}) {
  const template = ENGLISH_MESSAGES[key] || key;
  return template.replace(/\{([^}]+)\}/g, (_, name) => String(params[name] ?? ''));
}

for (const entity of ['modules', 'permissions']) {
  const descriptor = GOVERNANCE_CRUD_DESCRIPTORS[entity];
  assert.equal(descriptor.readonly, true, `${entity} catalog must be readonly`);
  assert.equal(descriptorAllowsAction(descriptor, 'create'), false, `${entity} catalog must not allow create`);
  assert.equal(descriptor.readonly_reason_key, 'governance.readonly.system_catalog', `${entity} catalog must carry the system readonly reason`);
  assert.deepEqual(descriptor.row_actions, [], `${entity} catalog must not expose row mutations`);
  assert.deepEqual(descriptor.form_actions, [], `${entity} catalog must not expose save actions`);
  assertLocalizedKey(descriptor.readonly_reason_key, `${entity} readonly reason`);
}

const moduleRoute = routeByName('admin-governance-modules');
const moduleRouteActions = routeActionsForContext(moduleRoute, platformAdminContext);
assert.equal(
  firstRouteActionByKind(moduleRouteActions, 'create'),
  null,
  'module system catalog must not expose create even for platform admin',
);
assert.equal(
  firstRouteActionByKind(moduleRouteActions, 'inspect')?.label_key,
  'governance.action.inspect_module_catalog',
  'module system catalog may only expose its entity-specific inspect route metadata',
);
assert.deepEqual(
  descriptorPageActions(GOVERNANCE_CRUD_DESCRIPTORS.modules, moduleRouteActions),
  [],
  'module system catalog must render no page action button instead of a generic create button',
);
assert.equal(
  moduleRoute.meta.readonly_reason_key,
  'governance.readonly.system_catalog',
  'module route metadata must expose the system catalog readonly reason',
);
assert.equal(
  governanceEmptyStateBody({
    descriptor: GOVERNANCE_CRUD_DESCRIPTORS.modules,
    routeMeta: moduleRoute.meta,
    singularLabel: 'Module',
    translate,
  }),
  'System catalog entries are managed by module descriptors.',
  'module empty state must show the readonly catalog reason instead of create copy',
);

const auditRoute = routeByName('admin-governance-audit-log');
assert.equal(
  auditRoute.meta.readonly_reason_key,
  'governance.readonly.audit_log',
  'audit log route metadata must expose an audit-specific readonly reason',
);
assert.equal(
  firstRouteActionByKind(routeActionsForContext(auditRoute, platformAdminContext), 'create'),
  null,
  'audit log must not expose create',
);
assert.deepEqual(
  descriptorPageActions(GOVERNANCE_CRUD_DESCRIPTORS['audit-log'], routeActionsForContext(auditRoute, platformAdminContext))
    .map((action) => [action.kind, action.label_key]),
  [['export', 'governance.action.export_audit_log']],
  'audit log page action bar must expose export, not generic create',
);
assert.equal(
  governanceEmptyStateBody({
    descriptor: GOVERNANCE_CRUD_DESCRIPTORS['audit-log'],
    routeMeta: auditRoute.meta,
    singularLabel: 'Audit Entry',
    translate,
  }),
  'Audit entries are generated by system activity.',
  'audit log empty state must use audit-specific readonly copy',
);

const portabilityRoute = routeByName('admin-governance-data-portability');
assert.equal(
  descriptorAllowsAction(GOVERNANCE_CRUD_DESCRIPTORS['data-portability'], 'create'),
  false,
  'data portability must not expose generic create semantics',
);
assert.equal(
  GOVERNANCE_CRUD_DESCRIPTORS['data-portability'].empty_state_body_key,
  'governance.empty_state.data_portability_body',
  'data portability must use an export/import empty-state body instead of generic create copy',
);
assert.deepEqual(
  descriptorPageActions(GOVERNANCE_CRUD_DESCRIPTORS['data-portability'], routeActionsForContext(portabilityRoute, platformAdminContext))
    .map((action) => [action.kind, action.label_key]),
  [
    ['export', 'governance.action.export_tenant_data'],
    ['import', 'governance.action.import_tenant_data'],
  ],
  'data portability page action bar must expose export/import actions, not generic create',
);
assertLocalizedKey(GOVERNANCE_CRUD_DESCRIPTORS['data-portability'].empty_state_body_key, 'data portability empty state body');
assert.equal(
  governanceEmptyStateBody({
    descriptor: GOVERNANCE_CRUD_DESCRIPTORS['data-portability'],
    routeMeta: portabilityRoute.meta,
    singularLabel: 'Export / Import Job',
    translate,
  }),
  'Use Export tenant data or Import tenant data to start a job.',
  'data portability empty state must point to export/import actions instead of generic create',
);

const governanceCrudSource = await readFile(path.join(root, 'src/modules/governance/pages/GovernanceCrudView.vue'), 'utf8');
assert.match(governanceCrudSource, /governanceEmptyStateBody/, 'governance CRUD view must use the shared no-create empty-state helper');
assert.match(governanceCrudSource, /:show-create="Boolean\(createAction\)"/, 'empty-state create affordance must remain gated by resolved create action');

for (const key of [
  'governance.empty_state.data_portability_body',
  'governance.empty_state.no_create_body',
  'governance.empty_state.readonly_body',
  'governance.readonly.audit_log',
]) {
  assertLocalizedKey(key, key);
}

console.log('[governance-readonly-create-actions-contract] PASS');
